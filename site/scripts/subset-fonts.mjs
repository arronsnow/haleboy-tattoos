// Writes src/styles/fonts.css: the fontsource @font-face rules for Latin plus only the
// Japanese unicode-range chunks that cover characters used in src/. The full Japanese
// CSS is ~490 rules (570 KB) and was render-blocking every page.
// Run after changing copy that adds new kanji/kana: `node scripts/subset-fonts.mjs`.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const SOURCES = [
  'dela-gothic-one/400.css',
  'zen-kaku-gothic-new/400.css',
  'zen-kaku-gothic-new/500.css',
  'zen-kaku-gothic-new/700.css',
];
const OUT = 'src/styles/fonts.css';

const files = (dir) => readdirSync(dir).flatMap((n) => {
  const p = join(dir, n);
  return statSync(p).isDirectory() ? files(p) : /\.(astro|ts|css|md)$/.test(n) && p !== join(OUT) ? [p] : [];
});
const used = new Set();
for (const f of files('src')) for (const ch of readFileSync(f, 'utf8')) if (ch.codePointAt(0) > 0xff) used.add(ch.codePointAt(0));

const covers = (range) => range.split(',').some((part) => {
  const [a, b = a] = part.trim().replace(/^U\+/i, '').split('-').map((h) => parseInt(h, 16));
  for (const cp of used) if (cp >= a && cp <= b) return true;
  return false;
});

let out = `/* Generated by scripts/subset-fonts.mjs. Do not edit; rerun it when copy adds new kanji/kana.\n   shortcut: Japanese glyphs not in src/ (e.g. typed in admin) fall back to the system font. */\n`;
for (const src of SOURCES) {
  const path = `node_modules/@fontsource/${src}`;
  const dir = relative('src/styles', join(path, '..')).replaceAll('\\', '/');
  for (const block of readFileSync(path, 'utf8').match(/@font-face\s*\{[^}]*\}/g)) {
    const range = block.match(/unicode-range:\s*([^;]+);/)[1];
    const latin = /latin-(ext-)?\d+-normal/.test(block);
    if (!latin && !covers(range)) continue;
    out += block
      .replace(/,\s*url\([^)]*\.woff\) format\('woff'\)/, '')
      .replace(/url\(\.\//g, `url(${dir}/`) + '\n';
  }
}
writeFileSync(OUT, out);
console.log(`${OUT}: ${(out.match(/@font-face/g) || []).length} rules, ${used.size} non-Latin-1 chars`);
